-- -----------------------------------------------------------------------------
-- 2. TABELA: supplier_cost_options (Catálogo Canônico das 42 Opções de Custo)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.supplier_cost_options (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code TEXT UNIQUE NOT NULL, -- Ex: 'TN-001' até 'TN-042'
  supplier_id UUID NOT NULL REFERENCES public.suppliers(id) ON DELETE CASCADE,
  supplier_name TEXT NOT NULL,
  service_name TEXT NOT NULL,
  variant TEXT,
  pricing_model TEXT NOT NULL DEFAULT 'per_person', -- 'per_person', 'fixed_vessel', 'fixed_jetski', 'per_vehicle_leg', 'quote_required'
  cost_adult NUMERIC DEFAULT 0,
  cost_child NUMERIC DEFAULT 0,
  cost_infant NUMERIC DEFAULT 0,
  cost_fixed NUMERIC DEFAULT 0,
  currency TEXT NOT NULL DEFAULT 'USD', -- 'USD', 'MXN', 'BRL'
  pricing_rule TEXT,
  external_fees_note TEXT,
  operation_days TEXT,
  operation_hours TEXT,
  duration TEXT,
  description TEXT,
  included TEXT,
  not_included TEXT,
  operational_notes TEXT,
  commercial_notes TEXT,
  pending_issues TEXT,
  source_reference TEXT,
  validation_status TEXT NOT NULL DEFAULT 'revisado', -- 'revisado', 'ressalva_conteudo', 'ressalva_tarifa', 'horario_pendente', 'info_pendente', 'estimado', 'sob_cotacao'
  public_tour_slug TEXT,
  active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- -----------------------------------------------------------------------------
-- 3. TABELA: supplier_cost_audit_log (Trilha de Auditoria de Custos)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.supplier_cost_audit_log (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  supplier_cost_option_id UUID REFERENCES public.supplier_cost_options(id) ON DELETE CASCADE,
  option_code TEXT NOT NULL,
  changed_by TEXT, -- Email ou ID do usuário
  change_type TEXT NOT NULL, -- 'INITIAL_IMPORT', 'UPDATE_COST', 'UPDATE_RULE', 'STATUS_CHANGE', 'OVERRIDE'
  previous_data JSONB,
  new_data JSONB,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- -----------------------------------------------------------------------------
-- 4. EVOLUÇÃO DA TABELA: contract_items (Snapshots Imutáveis de Reserva)
-- -----------------------------------------------------------------------------
ALTER TABLE public.contract_items
  ADD COLUMN IF NOT EXISTS supplier_cost_option_id UUID REFERENCES public.supplier_cost_options(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS tariff_code_snapshot TEXT,
  ADD COLUMN IF NOT EXISTS pricing_model_snapshot TEXT DEFAULT 'per_person',
  ADD COLUMN IF NOT EXISTS units_count INT DEFAULT 1,
  ADD COLUMN IF NOT EXISTS external_fees_snapshot TEXT,
  ADD COLUMN IF NOT EXISTS currency_exchange_rate NUMERIC DEFAULT 1,
  ADD COLUMN IF NOT EXISTS calculation_breakdown JSONB DEFAULT '{}'::jsonb;

-- -----------------------------------------------------------------------------
-- 5. TABELA: supplier_payments (Controle de Quitações e Pagamentos a Fornecedores)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.supplier_payments (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  supplier_id UUID NOT NULL REFERENCES public.suppliers(id) ON DELETE CASCADE,
  payment_date DATE NOT NULL,
  amount NUMERIC NOT NULL DEFAULT 0,
  currency TEXT NOT NULL DEFAULT 'USD',
  payment_method TEXT DEFAULT 'transferencia', -- transferencia, pix, efectivo, tarjeta
  reference_code TEXT, -- Número do comprovante ou ordem de transferência
  notes TEXT,
  created_by TEXT,
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.supplier_payment_allocations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  payment_id UUID NOT NULL REFERENCES public.supplier_payments(id) ON DELETE CASCADE,
  contract_item_id UUID NOT NULL REFERENCES public.contract_items(id) ON DELETE CASCADE,
  allocated_amount NUMERIC NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now(),
  UNIQUE(payment_id, contract_item_id)
);

